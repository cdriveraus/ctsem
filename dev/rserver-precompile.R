# Regenerates inst/julia/rserver/precompile_statements.jl: the methods a fresh
# ctsem session compiles in JuliaConnectoR's server and in Base for its types,
# which the CtsemRServer package (inst/julia/rserver/, R/ctJuliaServer.R)
# compiles into its image. Run after a JuliaConnectoR or Julia update, or when
# a first fit's compile time grows (the proposal's measurements are in
# review/PRECOMPILE-connector-proposal-2026-10-25.md).
#
#   Rscript dev/rserver-precompile.R            # from the package root
#
# The session is started by JuliaConnectoR itself, before ctsem asks for one,
# so it is the plain server that is traced -- ctsem adopts a session something
# else started (R/ctJuliaBridge.R) -- and then runs ctJuliaSetup() and a first
# fit, as a user's first call does. A statement is kept only where every module
# it names is one the package sees (Base, Core, the server's own and its
# imports): the engine's, ComponentArrays', and the session's `Main` closures
# compile at run time as before.
suppressMessages(devtools::load_all(".", compile = FALSE, quiet = TRUE))

.rserverKeep <- c("Base", "Core", "RConnector", "Sockets", "Logging", "Tables",
  "InteractiveUtils")

# The statements of trace file `path` the package can compile, in order, once.
.rserverStatements <- function(path) {
  lines <- readLines(path, warn = FALSE)
  lines <- lines[startsWith(lines, "precompile(")]
  modules <- regmatches(lines, gregexpr("(?<![.A-Za-z0-9_])[A-Z][A-Za-z0-9_]*(?=\\.)",
    lines, perl = TRUE))
  ok <- vapply(modules, function(m) all(m %in% .rserverKeep), logical(1))
  unique(lines[ok])
}

if (sys.nframe() == 0L) {
  trace <- normalizePath(tempfile("rserver-trace-", fileext = ".jl"), winslash = "/",
    mustWork = FALSE)
  Sys.setenv(JULIACONNECTOR_JULIAOPTS = paste0("--trace-compile=", trace))
  JuliaConnectoR:::startJulia()
  ctJuliaSetup()
  set.seed(1)
  d <- data.frame(id = rep(1:12, each = 6), time = rep(0:5, 12),
    Y1 = stats::rnorm(72))
  m <- suppressMessages(ctModel(type = "ct", manifestNames = "Y1", latentNames = "eta1",
    LAMBDA = matrix(1)))
  fit <- suppressWarnings(suppressMessages(ctFit(d, m, backend = "julia", cores = 1,
    verbose = 0)))
  invisible(summary(fit))
  JuliaConnectoR::stopJulia()
  Sys.sleep(1)
  kept <- .rserverStatements(trace)
  out <- file.path("inst", "julia", "rserver", "precompile_statements.jl")
  writeLines(c(
    paste0("# Generated by dev/rserver-precompile.R on ", Sys.Date(), " (JuliaConnectoR ",
      utils::packageVersion("JuliaConnectoR"), ", Julia ",
      .ctJuliaCachedVersion(.ctJuliaBin()), "): ", length(kept), " statements."),
    "# Read by CtsemRServer.jl, one statement a line; edit by regenerating.",
    kept), out)
  cat("Wrote", length(kept), "statements to", out, "\n")
}
